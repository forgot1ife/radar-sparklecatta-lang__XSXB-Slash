"""Build assets/parry/parry_builtin.js from the AI-generated source masks in assets/parry/builtin_src/.

These are the 格挡 tab's *built-in* textures: permanent click-to-use options inside their item panels.
They never take part in 🎲 random (random = seeded formulas only).
Clean-up: grey, black-level cut, gamma, radial edge fade so nothing touches the border, 256 px PNG, base64.
"""
import base64, io, json, pathlib
import numpy as np
from PIL import Image

HERE = pathlib.Path(__file__).parent
SRC = HERE / "builtin_src"
# key, file, label, item, black level, gamma, size
ITEMS = [
    ("nova", "banana_flash_nova.jpg", "★ 内置·十二芒", "star", 0.10, 1.4, 256),
    ("swordstar", "banana_flash_swordstar.jpg", "★ 内置·剑芒", "star", 0.08, 1.2, 256),
    ("flash_sphere", "banana_flash_sphere.jpg", "★ 内置·震波光球", "flash", 0.06, 1.05, 256),
    ("flash_ripple", "banana_flash_ripple.jpg", "★ 内置·水波震纹", "flash", 0.06, 1.05, 256),
    ("flash_caustic", "banana_flash_caustic.jpg", "★ 内置·焦散能量泡", "flash", 0.07, 1.08, 256),
    ("flash_sonic", "banana_flash_sonic.jpg", "★ 内置·音爆气环", "flash", 0.07, 1.08, 256),
    ("inksplash", "banana_ink_splash.jpg", "★ 内置·泼墨", "smoke", 0.12, 1.1, 256),
    ("smoke_wisps", "smoke_ash_wisps.jpg", "★ 内置·飞灰烟丝", "smoke", 0.10, 1.1, 256),
    ("smoke_cloud", "smoke_cloud_burst.jpg", "★ 内置·乱墨团雾", "smoke", 0.10, 1.1, 256),
    ("smoke_radial", "smoke_ink_radial.jpg", "★ 内置·放射飞白", "smoke", 0.10, 1.1, 256),
    ("ripple", "banana_refr_ripple.jpg", "★ 内置·涟漪", "refr", 0.05, 1.0, 256),
]

def clean(path, item, black, gamma, size):
    im = Image.open(path).convert("L")
    w, h = im.size
    s = min(w, h)
    im = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
    if item == "flash":
        raw = np.asarray(im).astype(np.float32) / 255.0
        yy, xx = np.mgrid[0:s, 0:s]
        rr_src = np.hypot(xx - (s - 1) / 2, yy - (s - 1) / 2) / (s / 2)
        fg = raw > max(0.12, black * 1.8)
        if fg.any():
            rmax = float(np.quantile(rr_src[fg], 0.995))
            if 0.55 < rmax < 0.945:
                sub = int(round(s * (rmax / 0.945)))
                off = (s - sub) // 2
                im = im.crop((off, off, off + sub, off + sub))
    im = im.resize((size, size), Image.Resampling.LANCZOS)
    a = np.asarray(im).astype(np.float32) / 255.0
    a = np.clip((a - black) / (1 - black), 0, 1) ** gamma
    y, x = np.mgrid[0:size, 0:size]
    r = np.hypot(x - (size - 1) / 2, y - (size - 1) / 2) / (size / 2)
    fade_w = 0.052 if item == "flash" else 0.08
    t = np.clip((0.992 - r) / fade_w, 0, 1)
    a *= t * t * (3.0 - 2.0 * t)  # strictly zero at border pixels (r >= 0.992) while staying rich up to r ~ 0.94
    return Image.fromarray((a * 255 + 0.5).astype(np.uint8), "L")

def main():
    out = {}
    for key, fn, label, item, black, gamma, size in ITEMS:
        im = clean(SRC / fn, item, black, gamma, size)
        buf = io.BytesIO()
        im.save(buf, "PNG", optimize=True)
        out[key] = {"label": label, "item": item, "src": "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()}
    js = "// generated by build_builtin.py: AI-generated built-in masks for the 格挡 tab (never used by 🎲 random)\nwindow.PARRY_BUILTIN=" + json.dumps(out, ensure_ascii=False) + ";\n"
    (HERE / "parry_builtin.js").write_text(js, encoding="utf-8")
    print({k: len(v["src"]) for k, v in out.items()})

if __name__ == "__main__":
    main()
